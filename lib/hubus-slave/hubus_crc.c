/* ====================================================================
   Bit-by-Bit Method (Compact, ~40 B code, slower)
   ==================================================================== */

/**
 * Bit-by-bit CRC8 calculation
 * More compact than lookup table; suitable for memory-constrained ATtiny
 * 
 * Algorithm:
 * For each byte:
 *   For each bit in byte (MSB first):
 *     Shift in bit, XOR with polynomial if MSB is 1
 */
uint8_t hubus_crc8(const uint8_t *data, uint8_t len)
{
    uint8_t crc = HUBUS_CRC8_INIT;
    
    for (uint8_t i = 0; i < len; i++) {
        crc ^= data[i];
        
        for (uint8_t bit = 0; bit < 8; bit++) {
            uint8_t msb = (crc & 0x80) != 0;
            crc = crc << 1;
            
            if (msb) {
                crc ^= HUBUS_CRC8_POLY;
            }
        }
    }
    
    return crc ^ HUBUS_CRC8_XOROUT;
}

