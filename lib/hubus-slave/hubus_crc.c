/* ====================================================================
   Validation (both methods share)
   ==================================================================== */

uint8_t hubus_crc8_validate(const uint8_t *data, uint8_t len)
{
    // CRC is valid if computing CRC over data+crc gives 0
    // (with xorout = 0, the table is computed such that this works)
    uint8_t computed_crc = hubus_crc8(data, len);
    return (computed_crc == HUBUS_CRC8_XOROUT) ? 1 : 0;
}
